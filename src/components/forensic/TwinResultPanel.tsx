import type { ForensicTwinResult } from '../../types/forensic';
import { ScenarioCard } from './ScenarioCard';
import { ZoneRankingTable } from './ZoneRankingTable';
import { ContradictionPanel } from './ContradictionPanel';
import { MechanismLedger } from './MechanismLedger';

interface Props {
  title: string;
  result?: ForensicTwinResult;
}

export function TwinResultPanel({ title, result }: Props) {
  if (!result) {
    return (
      <section className="border border-slate-300 bg-white rounded-lg p-3">
        <h3 className="font-bold">{title}</h3>
        <div className="text-sm text-slate-700">No run yet.</div>
      </section>
    );
  }

  return (
    <section className="border border-slate-300 bg-white rounded-lg p-3 space-y-3">
      <h3 className="font-bold">{title}</h3>
      <div className="text-xs">
        Run: {result.runId} | Latency: {result.latencyMs}ms | Tokens: {result.tokenUsage} | isSynthetic: {String(result.isSynthetic)}
      </div>
      <div className="text-xs text-slate-700">{result.uncertaintyStatement}</div>
      <div className="space-y-2">
        {result.scenarios.map((scenario) => (
          <div key={scenario.id}>
            <ScenarioCard scenario={scenario} />
          </div>
        ))}
      </div>
      <section className="space-y-1 text-sm">
        <h4 className="font-semibold">Recommended Next Actions</h4>
        {result.recommendedActions.map((action) => (
          <div key={action.id} className="border border-slate-200 rounded p-2">
            <div className="font-medium">{action.title}</div>
            <div>
              Priority: {action.priorityScore.toFixed(3)} | Class: {action.actionClass}
            </div>
            <div>{action.rationale}</div>
          </div>
        ))}
      </section>
      <ZoneRankingTable title="Ranked Candidate Zones" zones={result.rankedZones} />
      <ContradictionPanel contradictions={result.contradictions} />
      {result.twinId === 'twin_b' && <MechanismLedger ledger={result.mechanismLedger} />}
      <section className="text-xs bg-slate-50 border border-slate-200 rounded p-2">
        <h4 className="font-semibold">Audit Trail</h4>
        {result.auditReferences.map((reference) => (
          <div key={reference.resultId}>
            <div>Result ID: {reference.resultId}</div>
            <div>Generated by: {reference.generatedBy}</div>
            <div>Mechanisms: {reference.mechanismIds.join(', ') || 'none'}</div>
            <div>Evidence IDs: {reference.evidenceIds.join(', ')}</div>
            <div>Assumptions: {reference.assumptions.join(', ')}</div>
          </div>
        ))}
      </section>
    </section>
  );
}
